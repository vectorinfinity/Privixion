import {test,expect} from '@playwright/test';

test('review, edit, finalize, confirm and download a redacted document',async({page})=>{
  const failures:string[]=[]; page.on('pageerror',e=>failures.push(e.message));
  await page.goto('/');
  await expect(page.getByRole('heading',{name:'Welcome back.'})).toBeVisible();
  await page.getByLabel('Administrator password').fill('test-password-12345');
  await page.getByRole('button',{name:'Enter workspace'}).click();
  await expect(page.getByRole('heading',{name:'Document workspace'})).toBeVisible();
  await page.locator('input[type=file]').setInputFiles({name:'browser-fixture.txt',mimeType:'text/plain',buffer:Buffer.from('Email: redaction@example.com\nPAN ABCPD1234E\nReference REF-123456\nPUBLIC INFORMATION')});
  await expect(page.getByRole('heading',{name:'Redaction review'})).toBeVisible({timeout:30000});
  await expect(page.getByRole('button',{name:'Prepare final preview'})).toBeDisabled();
  await page.getByRole('button',{name:'Accept all pending'}).click();
  await page.getByLabel('Search sensitive terms').fill('REF-123456');
  await page.getByRole('button',{name:'Search',exact:true}).click();
  await expect(page.getByText('1 matches')).toBeVisible();
  await page.getByRole('button',{name:'Redact all',exact:true}).click();
  await page.getByRole('button',{name:'Undo',exact:true}).click();
  await page.getByRole('button',{name:'Redo',exact:true}).click();
  await page.getByRole('button',{name:'Save draft',exact:true}).click();
  await expect(page.getByRole('button',{name:'Save draft',exact:true})).toBeDisabled();
  await page.screenshot({path:'test-results/editor-desktop.png',fullPage:true});
  await page.getByRole('button',{name:'Prepare final preview'}).click();
  await page.getByRole('button',{name:'Review final PDF'}).click({timeout:30000});
  await expect(page.getByRole('dialog',{name:'Final PDF preview'})).toBeVisible();
  const image=page.getByRole('img',{name:'Final PDF page 1'});
  await expect(image).toBeVisible(); await expect.poll(()=>image.evaluate((img:HTMLImageElement)=>img.complete&&img.naturalWidth>0)).toBe(true);
  await page.screenshot({path:'test-results/final-preview.png',fullPage:true});
  await expect(page.getByRole('link',{name:'Download PDF'})).toHaveCount(0);
  await page.getByRole('button',{name:'Confirm reviewed export'}).click();
  const downloaded=page.waitForEvent('download');
  await page.getByRole('link',{name:'Download PDF',exact:true}).last().click();
  expect((await downloaded).suggestedFilename()).toMatch(/^redacted-.*\.pdf$/);
  await page.getByRole('button',{name:'Close final preview'}).click();
  await page.getByRole('button',{name:'Document audit history'}).click();
  await expect(page.getByText('export confirmed',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Close dialog'}).click();
  await page.getByLabel('Select browser-fixture.txt for batch download').check();
  const batch=page.waitForEvent('download');
  await page.getByRole('button',{name:'Download selected finalized documents'}).click();
  expect((await batch).suggestedFilename()).toBe('redacted-batch.zip');
  await page.setViewportSize({width:390,height:844});
  await page.screenshot({path:'test-results/editor-mobile.png',fullPage:true});
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth)).toBe(true);
  expect(failures).toEqual([]);
});

test('draw an area, apply a template, and delete document',async({page})=>{
  await page.goto('/');
  await page.getByLabel('Administrator password').fill('test-password-12345');
  await page.getByRole('button',{name:'Enter workspace'}).click();
  await page.locator('input[type=file]').setInputFiles({name:'manual-fixture.txt',mimeType:'text/plain',buffer:Buffer.from('Reference REF-123456\nPUBLIC INFORMATION')});
  await page.getByRole('button',{name:'manual-fixture.txt',exact:false}).click();
  await expect(page.getByRole('heading',{name:'Redaction review'})).toBeVisible({timeout:30000});
  await page.getByRole('button',{name:'Draw rectangle',exact:true}).click();
  const sheet=await page.locator('.page-sheet').boundingBox();
  if(!sheet)throw new Error('Missing page');
  await page.mouse.move(sheet.x+sheet.width*.1,sheet.y+sheet.height*.1); await page.mouse.down();
  await page.mouse.move(sheet.x+sheet.width*.4,sheet.y+sheet.height*.2); await page.mouse.up();
  await page.getByRole('button',{name:/^Selected \d+$/}).click();
  await expect(page.locator('.selection-card')).toHaveCount(1);
  await page.getByRole('button',{name:'Select text',exact:true}).click();
  await page.getByRole('button',{name:'Zoom in',exact:true}).click();
  const documents=await (await page.request.get('/api/documents')).json();
  const target=documents.find((d:{name:string})=>d.name==='manual-fixture.txt');
  const detail=await (await page.request.get(`/api/documents/${target.id}`)).json();
  const word=detail.pages[0].words.find((w:{text:string})=>w.text==='PUBLIC');
  expect(word).toBeTruthy();
  const bounds=await page.locator('.page-sheet').boundingBox();
  if(!bounds)throw new Error('Missing zoomed page');
  await page.mouse.click(bounds.x+(word.rect[0]+word.rect[2])/2*bounds.width,bounds.y+(word.rect[1]+word.rect[3])/2*bounds.height);
  await expect(page.locator('.selection-card')).toHaveCount(2);
  await page.getByRole('button',{name:'Rule templates',exact:true}).click();
  await page.getByLabel('Template name').fill('Internal references');
  await page.getByRole('button',{name:'Save template'}).click();
  await page.getByRole('button',{name:'Apply',exact:true}).click();
  await page.getByRole('button',{name:'Detections',exact:false}).click();
  await expect(page.getByText('REF-123456',{exact:true})).toBeVisible();
  await page.getByRole('button',{name:'Delete document',exact:true}).click();
  await page.getByRole('button',{name:'Delete permanently'}).click();
  await expect(page.getByRole('heading',{name:'Your next safe-to-share document starts here.'})).toBeVisible();
});
